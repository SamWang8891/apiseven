#!/usr/bin/env node
// Which subsystem each APISIX plugin belongs to, from the source tree: the http plugins are the
// modules in apisix/plugins/, the stream plugins those in apisix/stream/plugins/ (some, like
// limit-conn, are both). A module is <name>.lua, or <name>/init.lua when that file declares
// `plugin_name = "<name>"` (proxy-cache; other directories hold helpers). The lists let the stream route views name only the plugins that can
// run there, without the Admin API's plugin list (which needs a request and reflects config.yaml).
//
//   node dev/gen-plugin-subsystems.mjs [path/to/apisix]    default ~/apiseven-ref/apisix
//
// Writes web/src/plugins/subsystems.ts with sorted names. Node 22+, no dependencies.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(process.argv[2] ?? join(homedir(), 'apiseven-ref', 'apisix'));
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'web', 'src', 'plugins', 'subsystems.ts');

function modules(dir) {
  const path = join(ROOT, 'apisix', dir);
  const entries = readdirSync(path, { withFileTypes: true });
  const files = entries.filter((e) => e.isFile() && e.name.endsWith('.lua')).map((e) => e.name.slice(0, -'.lua'.length));
  const dirs = entries
    .filter((e) => e.isDirectory() && !files.includes(e.name))
    .filter((e) => {
      const init = join(path, e.name, 'init.lua');
      return existsSync(init) && readFileSync(init, 'utf8').includes(`plugin_name = "${e.name}"`);
    })
    .map((e) => e.name);
  return [...files, ...dirs].sort();
}

const http = modules('plugins');
const stream = modules(join('stream', 'plugins'));
const list = (names) => `[\n${names.map((n) => `  ${JSON.stringify(n)},`).join('\n')}\n]`;

writeFileSync(
  OUT,
  `// GENERATED by dev/gen-plugin-subsystems.mjs — do not edit. Regenerate with
//   node dev/gen-plugin-subsystems.mjs [path/to/apisix]   (default ~/apiseven-ref/apisix)
// The plugin modules of Apache APISIX's source tree, by subsystem.

/** The http subsystem's plugins (apisix/plugins/). */
export const HTTP_PLUGINS: readonly string[] = ${list(http)};

/** The stream subsystem's plugins (apisix/stream/plugins/). */
export const STREAM_PLUGINS: readonly string[] = ${list(stream)};
`,
);
console.log(`wrote ${OUT}: ${http.length} http, ${stream.length} stream`);
